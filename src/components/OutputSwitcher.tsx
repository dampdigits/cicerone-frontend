import React from 'react';
import {
  FileText,
  GitFork,
  Clock,
  Shield,
  Star,
  Copy,
  Download,
  Check,
  FileSearch,
  Sparkles,
} from 'lucide-react';
import { PipelineResult } from '../types/research';

export type OutputViewMode = 'markdown' | 'workflow' | 'discovery';

interface OutputSwitcherProps {
  result: PipelineResult;
  activeView: OutputViewMode;
  onViewChange: (view: OutputViewMode) => void;
  completedSubStepsCount: number;
  totalSubStepsCount: number;
  onRunFullResearch?: (provider: string) => void;
}

export const OutputSwitcher: React.FC<OutputSwitcherProps> = ({
  result,
  activeView,
  onViewChange,
  completedSubStepsCount,
  totalSubStepsCount,
  onRunFullResearch,
}) => {
  const [copied, setCopied] = React.useState(false);

  const json = result.json;
  const workflow = json?.workflow;
  const totals = workflow?.totals || json?.totals;
  const difficulty = workflow?.difficulty;
  const isDryRun = result.status === 'dry_run';
  const sourceUrlsCount = json?.source_urls?.length || 0;
  const discovery = json?.discovery;

  const handleCopyMarkdown = () => {
    if (result.markdown) {
      navigator.clipboard.writeText(result.markdown);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  const handleDownloadJson = () => {
    const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(result, null, 2));
    const dlAnchorElem = document.createElement('a');
    dlAnchorElem.setAttribute('href', dataStr);
    dlAnchorElem.setAttribute('download', `${(result.provider || 'oauth-research').toLowerCase()}-cicerone.json`);
    dlAnchorElem.click();
  };

  const formatMinutes = (minObj?: { min: number; max: number }) => {
    if (!minObj || (minObj.min === 0 && minObj.max === 0)) return 'N/A';
    if (minObj.min === minObj.max) return `${minObj.min}m`;
    return `${minObj.min}–${minObj.max}m`;
  };

  return (
    <div className="w-full max-w-7xl mx-auto space-y-4 mb-6">
      {/* Provider Hero / Stats Card */}
      <div className="bg-black rounded-2xl p-5 sm:p-6 border border-white/10 shadow-xl relative overflow-hidden">
        <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-6">
          {/* Left: Provider info */}
          <div className="space-y-2">
            <div className="flex items-center gap-3 flex-wrap">
              <h1 className="text-2xl sm:text-3xl font-extrabold text-white tracking-tight capitalize">
                {json?.display_name || result.provider}
              </h1>
              <span
                className={`text-xs px-2.5 py-0.5 rounded-full font-bold uppercase tracking-wider border ${
                  result.status === 'completed'
                    ? 'bg-navy-950 text-navy-300 border-navy-700'
                    : result.status === 'partial'
                    ? 'bg-neutral-900 text-neutral-300 border-neutral-700'
                    : 'bg-navy-950 text-navy-400 border-navy-800'
                }`}
              >
                {result.status === 'dry_run' ? 'Dry Run (Discovery Only)' : result.status}
              </span>
              {json?.auto_detected && (
                <span className="text-[11px] px-2 py-0.5 rounded-full bg-neutral-900 text-neutral-400 border border-neutral-800">
                  Domains Auto-detected
                </span>
              )}
            </div>
            <p className="text-xs sm:text-sm text-neutral-400">
              {isDryRun
                ? 'Discovery preview: Tavily mapped and filtered official documentation URLs without token cost.'
                : 'Generated by Cicerone pipeline using official documentation pages and verified quotes.'}
            </p>
          </div>

          {/* Right: Key metrics pills */}
          <div className="flex items-center gap-3 flex-wrap">
            {isDryRun ? (
              <>
                {/* Discovery Count */}
                <div className="bg-neutral-950 border border-neutral-800 px-3.5 py-2 rounded-xl flex items-center gap-2.5">
                  <div className="w-7 h-7 rounded-lg bg-navy-950 border border-navy-800 flex items-center justify-center text-navy-300">
                    <FileSearch className="w-4 h-4 text-navy-400" />
                  </div>
                  <div>
                    <div className="text-[10px] uppercase font-bold text-neutral-500 tracking-wider">Pages Mapped</div>
                    <div className="text-xs font-bold text-neutral-200">
                      {sourceUrlsCount} URLs <span className="text-neutral-500 font-normal">({discovery?.candidates || sourceUrlsCount} candidates)</span>
                    </div>
                  </div>
                </div>

                {/* LLM Tokens Cost */}
                <div className="bg-neutral-950 border border-neutral-800 px-3.5 py-2 rounded-xl flex items-center gap-2.5">
                  <div className="w-7 h-7 rounded-lg bg-navy-950 border border-navy-800 flex items-center justify-center text-navy-300">
                    <Shield className="w-4 h-4 text-navy-400" />
                  </div>
                  <div>
                    <div className="text-[10px] uppercase font-bold text-neutral-500 tracking-wider">Model Usage</div>
                    <div className="text-xs font-bold text-navy-300">
                      0 Tokens <span className="text-neutral-500 font-normal">(Free preview)</span>
                    </div>
                  </div>
                </div>
              </>
            ) : (
              <>
                {/* Difficulty rating */}
                {difficulty && difficulty.score !== null && (
                  <div
                    className="bg-neutral-950 border border-neutral-800 px-3.5 py-2 rounded-xl flex items-center gap-2.5"
                    title={difficulty.reasoning || difficulty.basis}
                  >
                    <div className="w-7 h-7 rounded-lg bg-navy-950 border border-navy-800 flex items-center justify-center text-navy-300">
                      <Star className="w-4 h-4 fill-navy-400 text-navy-400" />
                    </div>
                    <div>
                      <div className="text-[10px] uppercase font-bold text-neutral-500 tracking-wider">Difficulty</div>
                      <div className="text-xs font-bold text-neutral-200">
                        {difficulty.score}/5 <span className="text-neutral-400 font-normal">({difficulty.label || 'Standard'})</span>
                      </div>
                    </div>
                  </div>
                )}

                {/* Active Time */}
                {totals?.active_time_minutes && (
                  <div className="bg-neutral-950 border border-neutral-800 px-3.5 py-2 rounded-xl flex items-center gap-2.5">
                    <div className="w-7 h-7 rounded-lg bg-navy-950 border border-navy-800 flex items-center justify-center text-navy-300">
                      <Clock className="w-4 h-4 text-navy-400" />
                    </div>
                    <div>
                      <div className="text-[10px] uppercase font-bold text-neutral-500 tracking-wider">Active Time</div>
                      <div className="text-xs font-bold text-neutral-200">
                        Min: {formatMinutes(totals.active_time_minutes.minimum_setup)}
                        <span className="text-neutral-600 mx-1">|</span>
                        Prod: {formatMinutes(totals.active_time_minutes.full_production)}
                      </div>
                    </div>
                  </div>
                )}

                {/* Approvals */}
                {totals?.approvals_required && (
                  <div className="bg-neutral-950 border border-neutral-800 px-3.5 py-2 rounded-xl flex items-center gap-2.5">
                    <div className="w-7 h-7 rounded-lg bg-navy-950 border border-navy-800 flex items-center justify-center text-navy-300">
                      <Shield className="w-4 h-4 text-navy-400" />
                    </div>
                    <div>
                      <div className="text-[10px] uppercase font-bold text-neutral-500 tracking-wider">Approvals</div>
                      <div className="text-xs font-bold text-neutral-200">
                        {totals.approvals_required.always} Always
                        <span className="text-neutral-600 mx-1">/</span>
                        {totals.approvals_required.conditional} Cond.
                      </div>
                    </div>
                  </div>
                )}
              </>
            )}
          </div>
        </div>

        {/* Tab Switcher & Action buttons */}
        <div className="mt-6 pt-4 border-t border-neutral-850 flex flex-col sm:flex-row items-center justify-between gap-4">
          {/* Main Segmented Switcher */}
          <div className="bg-neutral-950 p-1.5 rounded-xl border border-neutral-800 flex items-center gap-1.5 w-full sm:w-auto shadow-inner flex-wrap">
            {/* Discovered URLs Tab (Always visible in dry_run or when URLs exist) */}
            {(isDryRun || sourceUrlsCount > 0) && (
              <button
                onClick={() => onViewChange('discovery')}
                className={`flex-1 sm:flex-initial flex items-center justify-center gap-2 px-4 py-2 rounded-lg text-xs font-bold transition-all ${
                  activeView === 'discovery'
                    ? 'bg-navy-600 text-white shadow-md shadow-navy-950 border border-navy-500/30'
                    : 'text-neutral-400 hover:text-white hover:bg-neutral-900'
                }`}
              >
                <FileSearch className="w-4 h-4" />
                <span>Discovered URLs</span>
                {sourceUrlsCount > 0 && (
                  <span
                    className={`text-[10px] px-1.5 py-0.2 rounded font-mono ${
                      activeView === 'discovery'
                        ? 'bg-navy-950 text-navy-200 font-extrabold'
                        : 'bg-neutral-900 text-neutral-400'
                    }`}
                  >
                    {sourceUrlsCount}
                  </span>
                )}
              </button>
            )}

            {/* Workflow Tab */}
            <button
              onClick={() => onViewChange('workflow')}
              className={`flex-1 sm:flex-initial flex items-center justify-center gap-2 px-4 py-2 rounded-lg text-xs font-bold transition-all ${
                activeView === 'workflow'
                  ? 'bg-navy-600 text-white shadow-md shadow-navy-950 border border-navy-500/30'
                  : 'text-neutral-400 hover:text-white hover:bg-neutral-900'
              }`}
            >
              <GitFork className="w-4 h-4" />
              <span>Interactive Workflow UI</span>
              {totalSubStepsCount > 0 && (
                <span
                  className={`text-[10px] px-1.5 py-0.2 rounded font-mono ${
                    activeView === 'workflow'
                      ? 'bg-navy-950 text-navy-200 font-extrabold'
                      : 'bg-neutral-900 text-neutral-400'
                  }`}
                >
                  {completedSubStepsCount}/{totalSubStepsCount}
                </span>
              )}
            </button>

            {/* Markdown Tab */}
            <button
              onClick={() => onViewChange('markdown')}
              className={`flex-1 sm:flex-initial flex items-center justify-center gap-2 px-4 py-2 rounded-lg text-xs font-bold transition-all ${
                activeView === 'markdown'
                  ? 'bg-navy-600 text-white shadow-md shadow-navy-950 border border-navy-500/30'
                  : 'text-neutral-400 hover:text-white hover:bg-neutral-900'
              }`}
            >
              <FileText className="w-4 h-4" />
              <span>Markdown Guide</span>
            </button>
          </div>

          {/* Action buttons */}
          <div className="flex items-center gap-2 self-end sm:self-auto flex-wrap">
            {isDryRun && onRunFullResearch && (
              <button
                onClick={() => onRunFullResearch(result.provider)}
                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold bg-gradient-to-r from-navy-700 to-navy-600 hover:from-navy-600 hover:to-navy-500 text-white border border-navy-500/30 transition-all shadow-md shadow-navy-950"
              >
                <Sparkles className="w-3.5 h-3.5 text-navy-300" />
                <span>Run Full Research</span>
              </button>
            )}

            <button
              onClick={handleCopyMarkdown}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-neutral-950 hover:bg-neutral-900 text-neutral-300 border border-neutral-800 hover:border-neutral-700 transition-colors"
              title="Copy the rendered Markdown documentation guide"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-navy-400" /> : <Copy className="w-3.5 h-3.5 text-neutral-400" />}
              <span>{copied ? 'Copied!' : 'Copy Markdown'}</span>
            </button>

            <button
              onClick={handleDownloadJson}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-neutral-950 hover:bg-neutral-900 text-neutral-300 border border-neutral-800 hover:border-neutral-700 transition-colors"
              title="Download raw JSON payload"
            >
              <Download className="w-3.5 h-3.5 text-neutral-400" />
              <span>Export JSON</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
