import React from 'react';
import {
  FileText,
  GitFork,
  Clock,
  Shield,
  Star,
  Copy,
  Download,
  Check,
  Sparkles,
} from 'lucide-react';
import { PipelineResult } from '../types/research';

export type OutputViewMode = 'markdown' | 'workflow';

interface OutputSwitcherProps {
  result: PipelineResult;
  activeView: OutputViewMode;
  onViewChange: (view: OutputViewMode) => void;
  completedSubStepsCount: number;
  totalSubStepsCount: number;
}

export const OutputSwitcher: React.FC<OutputSwitcherProps> = ({
  result,
  activeView,
  onViewChange,
  completedSubStepsCount,
  totalSubStepsCount,
}) => {
  const [copied, setCopied] = React.useState(false);

  const json = result.json;
  const workflow = json?.workflow;
  const totals = workflow?.totals || json?.totals;
  const difficulty = workflow?.difficulty;

  const handleCopyMarkdown = () => {
    if (result.markdown) {
      navigator.clipboard.writeText(result.markdown);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  const handleDownloadJson = () => {
    const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(result, null, 2));
    const dlAnchorElem = document.createElement('a');
    dlAnchorElem.setAttribute('href', dataStr);
    dlAnchorElem.setAttribute('download', `${(result.provider || 'oauth-research').toLowerCase()}-cicerone.json`);
    dlAnchorElem.click();
  };

  // Format active time minutes
  const formatMinutes = (minObj?: { min: number; max: number }) => {
    if (!minObj || (minObj.min === 0 && minObj.max === 0)) return 'N/A';
    if (minObj.min === minObj.max) return `${minObj.min}m`;
    return `${minObj.min}–${minObj.max}m`;
  };

  // Format wait days
  const formatWaitDays = (waitObj?: { min: number; max: number }) => {
    if (!waitObj || (waitObj.min === 0 && waitObj.max === 0)) return '0d';
    if (waitObj.min === waitObj.max) return `${waitObj.min}d`;
    return `${waitObj.min}–${waitObj.max}d`;
  };

  return (
    <div className="w-full max-w-7xl mx-auto space-y-4 mb-6">
      {/* Provider Hero / Stats Card */}
      <div className="glass-panel rounded-2xl p-5 sm:p-6 border border-slate-800 shadow-xl relative overflow-hidden">
        <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-6">
          {/* Left: Provider info */}
          <div className="space-y-2">
            <div className="flex items-center gap-3 flex-wrap">
              <h1 className="text-2xl sm:text-3xl font-extrabold text-white tracking-tight capitalize">
                {json?.display_name || result.provider}
              </h1>
              <span
                className={`text-xs px-2.5 py-0.5 rounded-full font-bold uppercase tracking-wider border ${
                  result.status === 'completed'
                    ? 'bg-emerald-500/20 text-emerald-300 border-emerald-500/30'
                    : result.status === 'partial'
                    ? 'bg-amber-500/20 text-amber-300 border-amber-500/30'
                    : 'bg-blue-500/20 text-blue-300 border-blue-500/30'
                }`}
              >
                {result.status}
              </span>
              {json?.auto_detected && (
                <span className="text-[11px] px-2 py-0.5 rounded-full bg-slate-800 text-slate-400 border border-slate-700">
                  Domains Auto-detected
                </span>
              )}
            </div>
            <p className="text-xs sm:text-sm text-slate-400">
              Generated by Cicerone pipeline using official documentation pages and verified quotes.
            </p>
          </div>

          {/* Right: Key metrics pills */}
          <div className="flex items-center gap-3 flex-wrap">
            {/* Difficulty rating */}
            {difficulty && difficulty.score !== null && (
              <div
                className="bg-slate-900/90 border border-slate-800 px-3.5 py-2 rounded-xl flex items-center gap-2.5"
                title={difficulty.reasoning || difficulty.basis}
              >
                <div className="w-7 h-7 rounded-lg bg-amber-500/10 border border-amber-500/20 flex items-center justify-center text-amber-400">
                  <Star className="w-4 h-4 fill-amber-400 text-amber-400" />
                </div>
                <div>
                  <div className="text-[10px] uppercase font-bold text-slate-500 tracking-wider">Difficulty</div>
                  <div className="text-xs font-bold text-slate-200">
                    {difficulty.score}/5 <span className="text-slate-400 font-normal">({difficulty.label || 'Standard'})</span>
                  </div>
                </div>
              </div>
            )}

            {/* Active Time */}
            {totals?.active_time_minutes && (
              <div className="bg-slate-900/90 border border-slate-800 px-3.5 py-2 rounded-xl flex items-center gap-2.5">
                <div className="w-7 h-7 rounded-lg bg-blue-500/10 border border-blue-500/20 flex items-center justify-center text-blue-400">
                  <Clock className="w-4 h-4" />
                </div>
                <div>
                  <div className="text-[10px] uppercase font-bold text-slate-500 tracking-wider">Active Time</div>
                  <div className="text-xs font-bold text-slate-200">
                    Min: {formatMinutes(totals.active_time_minutes.minimum_setup)}
                    <span className="text-slate-500 mx-1">|</span>
                    Prod: {formatMinutes(totals.active_time_minutes.full_production)}
                  </div>
                </div>
              </div>
            )}

            {/* Approvals */}
            {totals?.approvals_required && (
              <div className="bg-slate-900/90 border border-slate-800 px-3.5 py-2 rounded-xl flex items-center gap-2.5">
                <div className="w-7 h-7 rounded-lg bg-purple-500/10 border border-purple-500/20 flex items-center justify-center text-purple-400">
                  <Shield className="w-4 h-4" />
                </div>
                <div>
                  <div className="text-[10px] uppercase font-bold text-slate-500 tracking-wider">Approvals</div>
                  <div className="text-xs font-bold text-slate-200">
                    {totals.approvals_required.always} Always
                    <span className="text-slate-500 mx-1">/</span>
                    {totals.approvals_required.conditional} Cond.
                  </div>
                </div>
              </div>
            )}
          </div>
        </div>

        {/* Tab Switcher & Action buttons */}
        <div className="mt-6 pt-4 border-t border-slate-800 flex flex-col sm:flex-row items-center justify-between gap-4">
          {/* Main Segmented Switcher */}
          <div className="bg-slate-950 p-1.5 rounded-xl border border-slate-800 flex items-center gap-1.5 w-full sm:w-auto shadow-inner">
            <button
              onClick={() => onViewChange('workflow')}
              className={`flex-1 sm:flex-initial flex items-center justify-center gap-2 px-5 py-2 rounded-lg text-xs font-bold transition-all ${
                activeView === 'workflow'
                  ? 'bg-gradient-to-r from-brand-500 to-brand-600 text-slate-950 shadow-md shadow-brand-500/25'
                  : 'text-slate-400 hover:text-slate-200 hover:bg-slate-900'
              }`}
            >
              <GitFork className="w-4 h-4" />
              <span>Interactive Workflow UI</span>
              {totalSubStepsCount > 0 && (
                <span
                  className={`text-[10px] px-1.5 py-0.2 rounded font-mono ${
                    activeView === 'workflow'
                      ? 'bg-slate-950/20 text-slate-950 font-extrabold'
                      : 'bg-slate-800 text-slate-400'
                  }`}
                >
                  {completedSubStepsCount}/{totalSubStepsCount}
                </span>
              )}
            </button>

            <button
              onClick={() => onViewChange('markdown')}
              className={`flex-1 sm:flex-initial flex items-center justify-center gap-2 px-5 py-2 rounded-lg text-xs font-bold transition-all ${
                activeView === 'markdown'
                  ? 'bg-gradient-to-r from-brand-500 to-brand-600 text-slate-950 shadow-md shadow-brand-500/25'
                  : 'text-slate-400 hover:text-slate-200 hover:bg-slate-900'
              }`}
            >
              <FileText className="w-4 h-4" />
              <span>Markdown Guide</span>
            </button>
          </div>

          {/* Action buttons */}
          <div className="flex items-center gap-2 self-end sm:self-auto">
            <button
              onClick={handleCopyMarkdown}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-slate-900 hover:bg-slate-800 text-slate-300 border border-slate-800 hover:border-slate-700 transition-colors"
              title="Copy the rendered Markdown documentation guide"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-brand-400" /> : <Copy className="w-3.5 h-3.5 text-slate-400" />}
              <span>{copied ? 'Copied!' : 'Copy Markdown'}</span>
            </button>

            <button
              onClick={handleDownloadJson}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-slate-900 hover:bg-slate-800 text-slate-300 border border-slate-800 hover:border-slate-700 transition-colors"
              title="Download raw JSON payload"
            >
              <Download className="w-3.5 h-3.5 text-slate-400" />
              <span>Export JSON</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
